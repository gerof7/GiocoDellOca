package GiocoDellOca;

public class Casella {

	private int numero;
	private String descrizione;
	
	public Casella(int numero, String descrizione) {
		this.numero = numero;
		this.descrizione = descrizione;
	}

	public int getNumero() {
		return numero;
	}

	public String getDescrizione() {
		return descrizione;
	}
		
}
